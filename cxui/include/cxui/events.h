/// @defgroup cxui_events Events
/// @ingroup cxui
/// @{
/// Each widget has one **slot** per kind of event it raises, and each slot holds at most one
/// handler. A handler is a function plus captured values, set with the cxuiOn* macro for its
/// event, such as cxuiOnKey():
///
/// @code
///   static CxUiResult findKey(stvlist* cvars, CxUiKeyEvent* ev)
///   {
///       LogView* lv = stvlNextPtr(cvars);
///       if (ev->key != CXUI_KEY_Enter)
///           return CXUI_Default;
///       logviewFindNext(lv);
///       return CXUI_Handled;
///   }
///
///   cxuiOnKey(lv->find, findKey, stvar(ptr, lv));
/// @endcode
///
/// - **Setting a slot replaces its handler**, and destroys the old one along with its captured
///   values. A handler can safely replace or clear its own slot while it runs.
/// - **Captured values are copied**, and captured objects are held by reference until the handler
///   is replaced or the widget is destroyed. A handler rarely needs to capture its own widget:
///   the event says which widget it is for (`ev->base.current`).
/// - **Key, wheel and text events bubble.** If the handler returns CXUI_Default, or there is none, the
///   event goes on to the widget's parent, and so on up to the window. CXUI_Handled stops it and
///   suppresses the platform's own handling of it.
/// - **Handlers run on the UI thread**, and can do anything there, including destroying the
///   widget the event is for. The event struct is only valid during the call.
/// - Events that many parties may want to hear about, such as a widget being destroyed, are
///   notifications instead: a cchain on the widget (`destroyNotify`) that any number of closures
///   can be attached to.


/// @brief Payload for CXUI_EV_Activate
typedef struct CxUiActivateEvent {
    CxUiEvent base;
    uint64 item;   ///< A list's item index, a grid's row or tree node; 0 for buttons, links and menu items
} CxUiActivateEvent;

/// @brief Payload for CXUI_EV_Change
typedef struct CxUiChangeEvent {
    CxUiEvent base;
} CxUiChangeEvent;

/// @brief Payload for CXUI_EV_Commit
typedef struct CxUiCommitEvent {
    CxUiEvent base;
} CxUiCommitEvent;

/// @brief Payload for CXUI_EV_Key
typedef struct CxUiKeyEvent {
    CxUiEvent base;
    CxUiKey key;
    uint32 mods;       ///< CxUiModifiers held
    uint32 scancode;   ///< The platform's code for the physical key, for rare uses
    bool down;         ///< false when the key is released
    bool repeat;       ///< Generated by holding the key down
} CxUiKeyEvent;

/// What happened in a CxUiMouseEvent
enum CxUiMouseActions {
    CXUI_MOUSE_Down,
    CXUI_MOUSE_Up,
    CXUI_MOUSE_DoubleClick,
    CXUI_MOUSE_Move,
    CXUI_MOUSE_Enter,
    CXUI_MOUSE_Leave,
};

/// Mouse buttons, as values for CxUiMouseEvent::button and bits in CxUiMouseEvent::buttons
enum CxUiMouseButtons {
    CXUI_BTN_Left   = 0x01,
    CXUI_BTN_Middle = 0x02,
    CXUI_BTN_Right  = 0x04,
    CXUI_BTN_X1     = 0x08,
    CXUI_BTN_X2     = 0x10,
};

/// Flags in CxUiMouseEvent::flags
enum CxUiMouseFlags {
    /// An Up the platform never sent: it took the mouse away while a button was held, or
    /// cxuiWindowBeginDrag() gave the press to a window move
    CXUI_MOUSE_CaptureLost = 0x01,
};

/// @brief Payload for CXUI_EV_Mouse
///
/// While any button is held, the canvas that saw it go down gets every event until all are
/// released, even outside its bounds. While the pointer is locked (cxuiCanvasSetPointerLock()),
/// every event goes to the locked canvas, at the point where the lock began.
typedef struct CxUiMouseEvent {
    CxUiEvent base;
    uint32 action;    ///< CxUiMouseActions
    uint32 button;    ///< For Down, Up and DoubleClick: the CxUiMouseButtons value that changed
    uint32 buttons;   ///< CxUiMouseButtons held now
    uint32 mods;      ///< CxUiModifiers held
    uint32 flags;     ///< CxUiMouseFlags
    int32 x, y;       ///< Physical pixels from the canvas's top left; may be outside it
    /// For Move: how far the mouse moved since the canvas's last mouse event, in the canvas's
    /// units; 0 for the first move after Enter, and for other actions. While the pointer is locked,
    /// how far the mouse moved although the pointer stays put.
    float32 dx, dy;
} CxUiMouseEvent;

/// @brief Payload for CXUI_EV_Wheel
///
/// A handler that returns CXUI_Default lets a scroll box around the widget scroll instead; see
/// the canvas overview for how the rest of the gesture follows its first turn.
typedef struct CxUiWheelEvent {
    CxUiEvent base;
    float64 dx, dy;   ///< Distance turned, in notches; positive is right and down
    uint32 mods;      ///< CxUiModifiers held
    int32 x, y;       ///< Physical pixels from the target's top left
} CxUiWheelEvent;

/// Flags in CxUiFocusEvent::flags
enum CxUiFocusFlags {
    /// A window's activation: a pointer lock in it was let go as it became inactive, or taken
    /// again as it became active
    CXUI_FOCUS_PointerLock = 0x01,
};

/// @brief Payload for CXUI_EV_Focus
typedef struct CxUiFocusEvent {
    CxUiEvent base;
    bool gained;
    uint32 flags;   ///< CxUiFocusFlags
} CxUiFocusEvent;

/// @brief Payload for CXUI_EV_Paint
typedef struct CxUiPaintEvent {
    CxUiEvent base;
    CxUiDraw* draw;    ///< Draw here; valid only during the handler. NULL for a render view
    CxUiRect dirty;    ///< The area to draw, in the canvas's units; drawing outside it has no effect
} CxUiPaintEvent;

/// @brief Payload for CXUI_EV_Resize
typedef struct CxUiResizeEvent {
    CxUiEvent base;
    CxUiSize size;   ///< The new size: physical pixels for a window, the canvas's units for a canvas
} CxUiResizeEvent;

/// Why a window is being asked to close
enum CxUiCloseReasons {
    CXUI_CLOSE_User,     ///< The close box, Alt+F4, or the like
    CXUI_CLOSE_System,   ///< The system is shutting down or logging off
    CXUI_CLOSE_App,      ///< The program called cxuiWindowClose()
};

/// @brief Payload for CXUI_EV_Close
///
/// Returning CXUI_Handled keeps the window open.
typedef struct CxUiCloseEvent {
    CxUiEvent base;
    uint32 reason;   ///< CxUiCloseReasons
} CxUiCloseEvent;

/// Whether a window is minimized, maximized, fullscreen or none of those
enum CxUiWindowStates {
    CXUI_WINDOW_Normal,
    CXUI_WINDOW_Minimized,
    CXUI_WINDOW_Maximized,
    /// Fullscreen, in either CxUiFullscreen mode
    CXUI_WINDOW_Fullscreen,
};

/// @brief Payload for CXUI_EV_ShowState
///
/// Also raised, with the state unchanged, when the window becomes hidden behind others or shown
/// again (cxuiWindowOccluded()).
typedef struct CxUiShowStateEvent {
    CxUiEvent base;
    uint32 state;    ///< CxUiWindowStates
    bool occluded;   ///< Nothing of the window can be seen, so it needn't draw
} CxUiShowStateEvent;

/// @brief Payload for CXUI_EV_Move
typedef struct CxUiMoveEvent {
    CxUiEvent base;
    CxUiPoint pos;   ///< The window's new position, in the platform's screen units
} CxUiMoveEvent;

/// @brief Payload for CXUI_EV_DpiChanged
///
/// By the time it arrives, the window's canvases have their new sizes and are marked to be
/// painted again. Fonts made for the old scale should be made again.
typedef struct CxUiDpiChangedEvent {
    CxUiEvent base;
    float32 scale;      ///< The new scale: physical pixels per device-independent pixel
    float32 oldScale;   ///< The scale before
} CxUiDpiChangedEvent;

/// @brief Payload for CXUI_EV_ThemeChanged
///
/// Sent when a window's resolved theme changes: its mode was set, or the system's setting changed
/// under CXUI_Theme_System. Its canvases are already marked to be painted again.
typedef struct CxUiThemeChangedEvent {
    CxUiEvent base;
    uint32 theme;   ///< CXUI_Theme_Light or CXUI_Theme_Dark
} CxUiThemeChangedEvent;

/// How the user moved a scroll bar
typedef enum CxUiScrollReason {
    CXUI_SCROLL_Thumb,          ///< Dragging the thumb
    CXUI_SCROLL_Page,           ///< Clicking the track, a page at a time
    CXUI_SCROLL_Step,           ///< An arrow key
    CXUI_SCROLL_Wheel,          ///< The mouse wheel
    CXUI_SCROLL_ThumbGrabbed,   ///< The thumb was grabbed; pos is unchanged
    CXUI_SCROLL_ThumbReleased,  ///< The thumb was let go; pos is unchanged
} CxUiScrollReason;

/// @brief Payload for CXUI_EV_Scroll
///
/// Only the user's actions raise it, never cxuiDScrollBarSetPos().
typedef struct CxUiScrollEvent {
    CxUiEvent base;
    int64 pos;        ///< The new position, already set on the bar
    uint32 reason;    ///< CxUiScrollReason
} CxUiScrollEvent;

/// @brief Payload for CXUI_EV_Sort
///
/// The grid shows the arrow before raising it; the handler sorts the source and calls
/// cxuiGridReset().
typedef struct CxUiSortEvent {
    CxUiEvent base;
    int32 column;      ///< The column, from 0
    bool descending;   ///< Largest first
} CxUiSortEvent;

/// @brief Payload for CXUI_EV_Context
typedef struct CxUiContextEvent {
    CxUiEvent base;
    uint64 item;     ///< A grid's row or tree node, when onItem is set
    int32 column;    ///< A grid's column, from 0, or -1
    bool onItem;     ///< Over a grid's row, rather than its headers or the space below the rows
    bool header;     ///< Over a grid's column headers
    int32 x, y;      ///< Where a menu would go, in physical pixels from the widget's top left
} CxUiContextEvent;

/// @brief Payload for CXUI_EV_Expand
///
/// Raised before the node opens or closes, so a handler can add a node's children as it opens.
typedef struct CxUiExpandEvent {
    CxUiEvent base;
    uint64 item;     ///< The node, a CxUiNodeId
    bool expanded;   ///< true when it is opening
} CxUiExpandEvent;

/// @brief Payload for CXUI_EV_Check
///
/// Raised before the check box changes. Unless a handler handles it, the grid then sets it
/// through the source's CxUiGridEditable, as a CxUiListStore or CxUiTreeStore has.
typedef struct CxUiCheckEvent {
    CxUiEvent base;
    uint64 item;    ///< The grid's row or tree node
    int32 column;   ///< The column, from 0
    uint32 state;   ///< The CxUiCheckState it is changing to
} CxUiCheckEvent;

/// What a CxUiEditEvent is for
typedef enum CxUiEditStage {
    /// The editor has opened over the cell, with its text selected; handling it closes the editor
    CXUI_EDIT_Start,
    /// The user kept what was typed, and the editor has closed
    CXUI_EDIT_Commit,
    /// The user dropped what was typed, and the editor has closed
    CXUI_EDIT_Cancel,
} CxUiEditStage;

/// @brief Payload for CXUI_EV_Edit
///
/// At Start, a handler can change the editor (cxuiGridEditor()), such as to select only part of
/// the text. After a Commit, unless a handler handles it, the grid sets a changed text through the
/// source's CxUiGridEditable, as a CxUiListStore or CxUiTreeStore has.
typedef struct CxUiEditEvent {
    CxUiEvent base;
    uint64 item;    ///< The grid's row or tree node
    int32 column;   ///< The column, from 0
    uint32 stage;   ///< CxUiEditStage
    strref text;    ///< The cell's text at Start, and what was typed after; borrowed for the call
} CxUiEditEvent;

/// @brief Payload for CXUI_EV_Surface
///
/// When the surface is going, the handler must not return until the renderer has stopped using
/// it. A renderer on another thread needs a hand-off that the handler waits for; that thread must
/// not wait on cxuiCallSync() meanwhile, since the UI thread can't run the call until the handler
/// returns.
typedef struct CxUiSurfaceEvent {
    CxUiEvent base;
    /// true: the surface is there to present to (cxuiRenderViewSurface()). false: it goes when
    /// the handler returns, so the renderer must let go of it first.
    bool available;
} CxUiSurfaceEvent;

/// @brief Payload for CXUI_EV_Text
///
/// Text the user typed into a canvas with text input on (cxuiCanvasSetTextInput()), after the key
/// event for the key that typed it.
typedef struct CxUiTextEvent {
    CxUiEvent base;
    /// The characters, in UTF-8; never control characters. Borrowed for the call.
    strref text;
} CxUiTextEvent;

